;; Generates single-file/index.html from app/: inlines kitchen_sink.cljs and embeds
;; every local asset (images as data: URLs, include.html as a data: URL, page-demo.html
;; as srcdoc HTML), so the result needs nothing but the pinned jsdelivr URLs.
;;
;; Run from the repo root: bb build-single
(ns build-single
  (:require [babashka.fs :as fs]
            [cheshire.core :as json]
            [clojure.string :as str])
  (:import [java.util Base64]
           [java.net URLEncoder]))

(def public "app/public")
(def out "single-file/index.html")

(defn data-url [rel mime]
  (str "data:" mime ";base64,"
       (.encodeToString (Base64/getEncoder) (fs/read-all-bytes (fs/path public rel)))))

(defn html-data-url [rel]
  ;; URLEncoder uses + for spaces; data: URLs need %20
  (str "data:text/html;charset=utf-8,"
       (str/replace (URLEncoder/encode (slurp (str (fs/path public rel))) "UTF-8") "+" "%20")))

(def assets
  (merge {"avatar"    (data-url "img/avatar.png" "image/png")
          "bounce"    (data-url "img/bounce.gif" "image/gif")
          "dawn-gray" (data-url "img/dawn-gray.jpg" "image/jpeg")
          "include"   (html-data-url "include.html")
          "page-demo" (slurp (str (fs/path public "page-demo.html")))}
         (into {} (for [n ["dawn" "forest" "dusk" "glacier"]
                        suffix ["" "-thumb"]]
                    [(str n suffix) (data-url (str "img/" n suffix ".jpg") "image/jpeg")]))))

(defn script-safe [s]
  ;; keep "</script" out of inline <script> content
  (str/replace s "</" "<\\/"))

(defn inline-scittle [file]
  (let [src (slurp (str (fs/path public "cljs" file)))]
    (assert (not (str/includes? src "</script")) (str file " must not contain </script"))
    (str "<script type=\"application/x-scittle\">\n" src "</script>")))

(let [shell (slurp (str (fs/path public "index.html")))
      tag   "<script type=\"application/x-scittle\" src=\"cljs/kitchen_sink.cljs\"></script>"
      vtag  "<script type=\"application/x-scittle\" src=\"cljs/views.cljc\"></script>"
      _     (assert (str/includes? shell tag) "app shell must load cljs/kitchen_sink.cljs")
      _     (assert (str/includes? shell vtag) "app shell must load cljs/views.cljc")
      inline (str "<script>window.KS_MODE = \"single\";\n"
                  "window.KS_ASSETS = " (script-safe (json/generate-string assets)) ";</script>\n"
                  (inline-scittle "kitchen_sink.cljs"))
      html  (-> shell
                (str/replace vtag (inline-scittle "views.cljc"))
                (str/replace tag inline)
                (str/replace "<!-- The whole UI lives in this file; the bb server pushes a reload when it changes. -->"
                             "<!-- GENERATED by scripts/build_single.clj from app/ - edit app/, then run `bb build-single`. -->"))]
  (fs/create-dirs (fs/parent out))
  (spit out html)
  (println (format "wrote %s (%d KB)" out (quot (count html) 1024))))
